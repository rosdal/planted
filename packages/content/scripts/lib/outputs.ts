import { join } from 'node:path';
import type { ContentConfig, MapData } from '../../src/schema';
import { type Extracted, extractMap } from './extract';
import { stableStringify } from './json';
import { MAPS_DIR, ROOT, readMapSources } from './repo';

/**
 * Every file the extractor writes into the source tree, by absolute path. `pnpm content:check`
 * regenerates these in memory and fails if the committed copies differ, so nobody hand-edits
 * `map.json` and a forgotten `content:extract` can't ship.
 */
export type Outputs = Map<string, string>;

export async function extractOne(mapId: string): Promise<Extracted> {
  const { meta, sources } = await readMapSources(join(MAPS_DIR, mapId));
  return extractMap(meta, sources);
}

export function mapOutputs(mapId: string, { map, art }: Extracted): Outputs {
  const dir = join(MAPS_DIR, mapId);
  const out: Outputs = new Map([[join(dir, 'map.json'), stableStringify(map, true)]]);
  for (const [floorId, svg] of Object.entries(art)) {
    out.set(join(dir, 'art', `${floorId}.svg`), `${svg}\n`);
  }
  return out;
}

/** `src/maps.gen.ts`: what the server and the app bundle about each map. */
export function summaryOutput(config: ContentConfig, maps: MapData[]): Outputs {
  const summary = config.maps.map((id) => {
    const map = maps.find((m) => m.id === id);
    if (!map) throw new Error(`content.json lists ${id}, which wasn't extracted`);
    return { id, name: map.name, floors: map.floors.map((f) => ({ id: f.id, label: f.label })) };
  });
  const body = [
    '// Generated by `pnpm content:extract`; do not edit.',
    '',
    'export type MapSummary = {',
    '  id: string;',
    '  name: string;',
    '  /** Bottom to top. */',
    '  floors: readonly { id: string; label: string }[];',
    '};',
    '',
    `export const MAPS: readonly MapSummary[] = ${JSON.stringify(summary, null, 2)};`,
    '',
  ].join('\n');
  return new Map([[join(ROOT, 'src', 'maps.gen.ts'), body]]);
}
